/**
 * Location formats:
 *   postgres://...        production Postgres via pg
 *   memory (or unset)     in-memory PGlite (tests)
 *   pglite:<dir>          persistent PGlite for local dev (real Postgres engine, no server needed)
 */
export async function openDb(location = 'memory'): Promise<Db> {
  const driver = /^postgres(ql)?:\/\//.test(location) ? pgDriver(location) : await pgliteDriver(location);
  const db = new Db(driver);
  await db.script(SCHEMA);
  await migrate(db);
  return db;
}


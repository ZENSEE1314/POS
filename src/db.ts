/** BIGINT/NUMERIC come back as strings by default; every money/time column here is a safe integer. */
const OID_INT8 = 20;
const OID_NUMERIC = 1700;
const toNumber = (v: string) => Number(v);
pg.types.setTypeParser(OID_INT8, toNumber);
pg.types.setTypeParser(OID_NUMERIC, toNumber);

interface Conn {
  exec(sql: string, params?: unknown[]): Promise<{ rows: any[]; count: number }>;
}
interface Driver {
  conn: Conn;
  transaction<T>(fn: (c: Conn) => Promise<T>): Promise<T>;
  close(): Promise<void>;
  script(sql: string): Promise<void>;
}

/** Converts `?` placeholders to `$n` so SQL stays readable. */
function numbered(sql: string): string {
  let i = 0;
  return sql.replace(/\?/g, () => `$${++i}`);
}

export class Db {
  private driver: Driver;
  private conn: Conn;
  private inTx: boolean;
  private savepoints = 0;

  constructor(driver: Driver, conn: Conn = driver.conn, inTx = false) {
    this.driver = driver;
    this.conn = conn;
    this.inTx = inTx;
  }

  async all<T = any>(sql: string, params: unknown[] = []): Promise<T[]> {
    return (await this.conn.exec(numbered(sql), params)).rows as T[];
  }

  async one<T = any>(sql: string, params: unknown[] = []): Promise<T | undefined> {
    return (await this.all<T>(sql, params))[0];
  }

  /** Returns the number of affected rows. */
  async run(sql: string, params: unknown[] = []): Promise<number> {
    return (await this.conn.exec(numbered(sql), params)).count;
  }

  /** INSERT ... RETURNING id helper. */
  async insert(sql: string, params: unknown[] = []): Promise<number> {
    const row = await this.one<{ id: number }>(`${sql} RETURNING id`, params);
    return row!.id;
  }

  /**
   * Runs fn atomically. Nested calls become savepoints of the outer transaction, so
   * "settle inside a payment" rolls back together with it. Always use the `t` you are given.
   */
  async tx<T>(fn: (t: Db) => Promise<T>): Promise<T> {
    if (!this.inTx) return this.driver.transaction((c) => fn(new Db(this.driver, c, true)));
    const sp = `sp${++this.savepoints}`;
    await this.conn.exec(`SAVEPOINT ${sp}`);
    try {
      const out = await fn(this);
      await this.conn.exec(`RELEASE SAVEPOINT ${sp}`);
      return out;
    } catch (e) {
      await this.conn.exec(`ROLLBACK TO SAVEPOINT ${sp}`);
      await this.conn.exec(`RELEASE SAVEPOINT ${sp}`);
      throw e;
    }
  }

  close(): Promise<void> {
    return this.driver.close();
  }

  script(sql: string): Promise<void> {
    return this.driver.script(sql);
  }
}


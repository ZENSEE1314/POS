async function migrate(db: Db): Promise<void> {
  await db.script('CREATE TABLE IF NOT EXISTS schema_migrations (id INT PRIMARY KEY, applied_at BIGINT NOT NULL)');
  for (const m of MIGRATIONS) {
    await db.tx(async (t) => {
      // advisory lock so two app instances booting together do not both migrate
      await t.run('SELECT pg_advisory_xact_lock(7340211)');
      if (await t.one('SELECT 1 AS x FROM schema_migrations WHERE id = ?', [m.id])) return;
      for (const sql of m.statements) await t.run(sql);
      await t.run('INSERT INTO schema_migrations (id, applied_at) VALUES (?,?)', [m.id, Date.now()]);
    });
  }
}

function pgDriver(url: string): Driver {
  const pool = new pg.Pool({ connectionString: url, max: 10 });
  const wrap = (c: { query: (s: string, p?: unknown[]) => Promise<any> }): Conn => ({
    exec: async (sql, params) => {
      const r = await c.query(sql, params);
      return { rows: r.rows, count: r.rowCount ?? 0 };
    },
  });
  return {
    conn: wrap(pool),
    async transaction(fn) {
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        const out = await fn(wrap(client));
        await client.query('COMMIT');
        return out;
      } catch (e) {
        await client.query('ROLLBACK');
        throw e;
      } finally {
        client.release();
      }
    },
    close: () => pool.end(),
    script: async (sql) => {
      await pool.query(sql);
    },
  };
}

async function pgliteDriver(location: string): Promise<Driver> {
  const { PGlite } = await import('@electric-sql/pglite');
  const dir = location.startsWith('pglite:') ? location.slice('pglite:'.length) : undefined;
  if (dir) mkdirSync(dir, { recursive: true });
  const lite = new PGlite(dir);
  // PGlite hands back BIGINT/NUMERIC as BigInt or string depending on size; normalise to numbers like the pg driver.
  const numericColumns = (fields: Array<{ name: string; dataTypeID: number }>) =>
    fields.filter((f) => f.dataTypeID === OID_INT8 || f.dataTypeID === OID_NUMERIC).map((f) => f.name);
  const wrap = (c: { query: (s: string, p?: unknown[]) => Promise<any> }): Conn => ({
    exec: async (sql, params) => {
      const r = await c.query(sql, params);
      const cols = numericColumns(r.fields ?? []);
      for (const row of r.rows) for (const col of cols) if (row[col] != null) row[col] = Number(row[col]);
      return { rows: r.rows, count: r.affectedRows ?? 0 };
    },
  });
  return {
    conn: wrap(lite),
    transaction: (fn) => lite.transaction((t) => fn(wrap(t))),
    close: () => lite.close(),
    script: async (sql) => {
      await lite.exec(sql);
    },
  };
}

export function audit(
  db: Db,
  who: { tenantId?: number | null; storeId?: number | null; actorId?: number | null },
  action: string, entity: string, entityId: number | null, detail: unknown = {},
): Promise<number> {
  return db.run('INSERT INTO audit (ts, tenant_id, store_id, actor_id, action, entity, entity_id, detail) VALUES (?,?,?,?,?,?,?,?)',
    [Date.now(), who.tenantId ?? null, who.storeId ?? null, who.actorId ?? null, action, entity, entityId, JSON.stringify(detail)]);
}

